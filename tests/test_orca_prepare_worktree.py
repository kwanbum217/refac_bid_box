def test_non_git_target_is_rejected_before_any_preparation(
    mock_gemini_env, fake_git_worktree, tmp_path: Path, capsys
):
    """비Git 디렉터리에는 .env·신뢰 설정·훅을 절대 변경하지 않습니다."""
