def _create_fake_pre_commit_installer():
    def fake_install_pre_commit(worktree_path, repo_path):
        hooks_dir = orca_prepare_worktree.get_git_hooks_path(worktree_path)
        if hooks_dir:
            hooks_dir.mkdir(parents=True, exist_ok=True)
            hook_file = hooks_dir / "pre-commit"
            hook_file.write_text(
                "#!/bin/sh\n# File generated by pre-commit\nexit 0\n", encoding="utf-8"
            )
            hook_file.chmod(0o755)
            return True, f"[pre-commit] 설치 완료: {hook_file}"
        return False, "[pre-commit] 설치 실패"

    return fake_install_pre_commit


def test_unprepared_worktree_check_fails(mock_gemini_env, fake_git_worktree, capsys):
    """준비되지 않은 상태에서 --check 가 종료 코드 1 을 내는지 검증합니다."""
    wt = fake_git_worktree["worktree"]
    repo = fake_git_worktree["repo"]

    # 아직 .env 가 없고 신뢰 등록도 안 됨
    exit_code = orca_prepare_worktree.prepare_worktree(wt, repo, check=True)
    captured = capsys.readouterr()

    assert exit_code == 1
    assert "[.env] 미준비" in captured.out
    assert "[신뢰] 미준비" in captured.out
    # check 모드에서는 파일을 생성하지 않음
    assert not (wt / ".env").exists()


def test_prepare_worktree_then_check_passes(
    mock_gemini_env, fake_git_worktree, monkeypatch, capsys
):
    """준비 실행 후 모든 항목이 갖춰지고 --check 가 0 을 반환하는지 검증합니다."""
    wt = fake_git_worktree["worktree"]
    repo = fake_git_worktree["repo"]

    monkeypatch.setattr(
        orca_prepare_worktree,
        "install_pre_commit_hook",
        _create_fake_pre_commit_installer(),
    )

    # 1. 준비 실행
    exit_code = orca_prepare_worktree.prepare_worktree(wt, repo, check=False)
    assert exit_code == 0

    # 2. 결과 검증
    # (a) .env 복사 확인
    assert (wt / ".env").is_file()
    assert (wt / ".env").read_text(encoding="utf-8") == (repo / ".env").read_text(encoding="utf-8")

    # (b) 신뢰 등록 확인
    settings_data = json.loads(mock_gemini_env["settings_path"].read_text(encoding="utf-8"))
    assert str(wt.resolve()) in settings_data["trustedWorkspaces"]
    folders_data = json.loads(mock_gemini_env["trusted_folders_path"].read_text(encoding="utf-8"))
    assert str(wt.resolve()).lower() in folders_data

    # (c) pre-commit 훅 확인
    assert orca_prepare_worktree.is_pre_commit_installed(wt)

    # 3. 준비 후 --check 실행 시 0 반환
    capsys.readouterr()  # 버퍼 비우기
    check_exit_code = orca_prepare_worktree.prepare_worktree(wt, repo, check=True)
    captured = capsys.readouterr()

    assert check_exit_code == 0
    assert "[.env] 이미 준비됨" in captured.out
    assert "[신뢰] 이미 신뢰됨" in captured.out
    assert "[pre-commit] 이미 준비됨" in captured.out


